const fs=require('fs'),vm=require('vm'),assert=require('node:assert/strict');
const harness=fs.readFileSync('tests/ui_monitor.cjs','utf8').split('const frame={')[0];
eval('(()=>{'+harness.replace("const fs=require('fs'),vm=require('vm'),assert=require('node:assert/strict');",'')+';globalThis.playerHarness={context,el};})()');
const {context,el}=globalThis.playerHarness;
const settings=()=>JSON.parse(JSON.stringify(context.settings().player_rcg));
assert.deepEqual(settings(),{enabled:false,left:[],right:[]});
el('playerRcgEnabled').checked=true;el('playerRcgEnabled').change();
assert.equal(el('playerRcgTeams').hidden,false);
el('playerRcgLeft').checked=true;el('playerRcgLeft').change();
assert.equal(el('playerRcgLeftNumbers').hidden,false);
el('playerRcg-left-1').checked=true;el('playerRcg-left-11').checked=true;
el('playerRcgRight').checked=true;el('playerRcg-right-2').checked=true;
assert.deepEqual(settings(),{enabled:true,left:[1,11],right:[2]});
el('playerRcgLeft').checked=false;el('playerRcgLeft').change();
assert.equal(el('playerRcgLeftNumbers').hidden,true);
assert.deepEqual(settings(),{enabled:true,left:[],right:[2]});
el('playerRcgEnabled').checked=false;el('playerRcgEnabled').change();
assert.equal(el('playerRcgTeams').hidden,true);
assert.deepEqual(settings(),{enabled:false,left:[],right:[]});
console.log('PASS: player RCG selection follows master/team toggles and selected uniforms');
